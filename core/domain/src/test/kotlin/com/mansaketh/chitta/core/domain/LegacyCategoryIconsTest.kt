    @Test fun everyOldPictureHasAnIcon() {
        val missing = oldPictures.filter { LegacyCategoryIcons.keyForPicture("$it.png") == null }
        assertTrue(missing.isEmpty(), "no icon for: $missing")
    }

    @Test fun namesAreReadTheWayTheOldAppStoredThem() {
        assertEquals("fork-knife", LegacyCategoryIcons.keyForPicture("cutlery.png"))
        assertEquals("car", LegacyCategoryIcons.keyForPicture("Car(2).PNG"))
        assertEquals("shopping-cart", LegacyCategoryIcons.keyForPicture("assets/categories/groceries.png"))
        assertEquals("hand-withdraw", LegacyCategoryIcons.keyForPicture("atm-machine(1).png"))
    }

    @Test fun anOwnPickOrNothingIsNotAnOldPicture() {
        assertNull(LegacyCategoryIcons.keyForPicture("ph:fork-knife"))
        assertNull(LegacyCategoryIcons.keyForPicture(null))
        assertNull(LegacyCategoryIcons.keyForPicture(""))
        assertNull(LegacyCategoryIcons.keyForPicture("never-heard-of-it.png"))
    }

    @Test fun categoryNamesGiveAGuessWhenThePictureIsUnknown() {
        assertEquals("fork-knife", LegacyCategoryIcons.keyForName("Dining"))
        assertEquals("shopping-cart", LegacyCategoryIcons.keyForName("Groceries"))
        assertEquals("bus", LegacyCategoryIcons.keyForName("Transit"))
        assertEquals("receipt", LegacyCategoryIcons.keyForName("Bills & Fees"))
        assertEquals("film-strip", LegacyCategoryIcons.keyForName("Entertainment"))
        assertNull(LegacyCategoryIcons.keyForName("Zzz"))
        assertNull(LegacyCategoryIcons.keyForName(null))
    }
